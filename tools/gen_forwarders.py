r"""Generate a header that forwards every export of a system DLL (proxy-DLL boilerplate).

usage: python tools/gen_forwarders.py C:\Windows\System32\winmm.dll src/probe_control/fwd_winmm.h
"""
import os, sys, pefile

src, out = sys.argv[1], sys.argv[2]
stem = os.path.splitext(os.path.basename(src))[0].lower()
pe = pefile.PE(src, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
target = src.replace("\\", "\\\\")[:-4]  # strip .dll; the linker wants "path.Export"
lines = [f"// Generated by tools/gen_forwarders.py from {os.path.basename(src)}: forwards every export to the real system DLL.",
         "#pragma once"]
for s in pe.DIRECTORY_ENTRY_EXPORT.symbols:
    if s.name:
        n = s.name.decode()
        lines.append(f'#pragma comment(linker, "/export:{n}={target}.{n},@{s.ordinal}")')
    else:
        lines.append(f'#pragma comment(linker, "/export:__ord{s.ordinal}={target}.#{s.ordinal},@{s.ordinal},NONAME")')
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print(f"{out}: {len(lines) - 2} forwards")
